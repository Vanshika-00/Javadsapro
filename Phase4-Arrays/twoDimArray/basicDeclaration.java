package twoDimArray;

public class basicDeclaration {

    

    public static void main(String[] args) {

        int [][] grid = new int [3][4]; // 3 rows and 4 columns
        grid[2][3] = 5; // Assigning value to the last element of the 2D array

        System.out.println(grid[2][3]);
        System.out.println(grid[0][0]);
    
}
}
